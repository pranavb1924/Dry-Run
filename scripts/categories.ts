// Groups the state's 426 merchant category descriptions into the spend
// categories that rules are written against.
//
// The descriptions are cut off at 40 characters, and hundreds of them are
// single airline, hotel or car rental brands ("DELTA", "SWISSOTEL",
// "HERTZ CORPORATION"), so the rules below match keywords and brand names.
// The first rule that matches wins, so the order matters: "AIR CONDITIONING"
// has to be claimed before the airfare rule sees the word AIR.

